function fmt(n: number) {
  return n >= 1_000_000 ? `${(n / 1_000_000).toFixed(1)}M`
       : n >= 1000      ? `${(n / 1000).toFixed(0)}K`
       : String(n);
}

function buildAutoUrl(platform: string, username: string): string {
  if (!username) return "";
  const u = username.replace(/^@/, "");
  if (platform === "tiktok" || platform === "tiktok_monetized") return `https://www.tiktok.com/@${u}`;
  if (platform === "instagram") return `https://www.instagram.com/${u}`;
  if (platform === "facebook") return `https://www.facebook.com/${u}`;
  if (platform === "snapchat") return `https://www.snapchat.com/add/${u}`;
  return "";
}

function isAutoGeneratedUrl(url: string): boolean {
  if (!url) return true;
  return (
    /^https:\/\/www\.tiktok\.com\/@/.test(url) ||
    /^https:\/\/www\.instagram\.com\//.test(url) ||
    /^https:\/\/www\.facebook\.com\//.test(url) ||
    /^https:\/\/www\.snapchat\.com\/add\//.test(url)
  );
}

